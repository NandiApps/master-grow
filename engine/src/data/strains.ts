export function getStrain(strainId: string): StrainGenetics {
  return STRAINS_DATABASE[strainId] || STRAINS_DATABASE["blue-dream"];
}

export function getAllStrains(): StrainGenetics[] {
  return Object.values(STRAINS_DATABASE);
}

export function getStrainsByDifficulty(
  difficulty: "beginner" | "intermediate"
): StrainGenetics[] {
  return Object.values(STRAINS_DATABASE).filter(
    (strain) => strain.difficulty === difficulty
  );
}
