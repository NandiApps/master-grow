export function getStrain(strainId: string): StrainGenetics {
  const strain = STRAINS_DATABASE[strainId];
  if (!strain) {
    throw new Error(`Strain not found: ${strainId}`);
  }
  return strain;
}

export function listStrains(): StrainGenetics[] {
  return Object.values(STRAINS_DATABASE);
}

export function listStrainsByDifficulty(
  difficulty: "beginner" | "intermediate"
): StrainGenetics[] {
  return Object.values(STRAINS_DATABASE).filter(
    (s) => s.difficulty === difficulty
  );
}
